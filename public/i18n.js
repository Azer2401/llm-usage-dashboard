// Current language
window.currentLang = localStorage.getItem('llm_dashboard_lang') || 'en';

window.t = function(key, vars = {}) {
  let str = (TRANSLATIONS[currentLang] || TRANSLATIONS.en)[key] || key;
  for (const [k, v] of Object.entries(vars)) {
    str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
  }
  return str;
};

window.setLang = function(lang) {
  currentLang = lang;
  localStorage.setItem('llm_dashboard_lang', lang);
  document.documentElement.setAttribute('data-lang', lang);
  document.getElementById('lang-toggle').textContent = lang === 'en' ? '🇮🇩 ID' : '🇬🇧 EN';
  // Re-render current page
  if (window.router) router.render();
};
